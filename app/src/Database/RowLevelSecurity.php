<?php
declare(strict_types=1);

namespace App\Database;

use InvalidArgumentException;

/**
 * SQL builders for the row-level security design (ADR-0005 section 1, layer 2; task RLS-SEC-001).
 *
 * Migrations call these so every table and function follows ONE pattern. Nothing here runs SQL: each method returns
 * statements for `$this->execute()`.
 *
 * ## Adding a scoped domain table (units, fees, payments, ...)
 *
 * The table needs a NOT NULL `development_id` and an index that starts with it. In its migration, as the migration
 * (owner) login:
 *
 * ```php
 * $this->execute('CREATE TABLE units (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, development_id bigint NOT NULL REFERENCES developments (id), ...)');
 * foreach (RowLevelSecurity::scopedDomainTable('units') as $sql) {
 *     $this->execute($sql);
 * }
 * ```
 *
 * and in `down()` drop the table (its policies go with it). The statements enable AND force row-level security,
 * create one policy per command (the read predicate would otherwise also apply to writes), and grant the runtime
 * role only the commands the policies allow. Per-role limits (a resident cannot edit a fee) stay in layer 1.
 *
 * A table whose reads and writes follow the permission catalogue (units, sections, ...) uses
 * `managedDomainTable()`: SELECT only in the developments where the session holds the read code, INSERT and UPDATE
 * only where it holds the write code (both through `permission_dev_ids`), DELETE for the super-administrator only.
 *
 * A catalogue whose `development_id` may be NULL (NULL = global) uses `catalogTable()` instead. A table that must
 * not be written directly (people, users) is written by hand: enable it with `enable()`, add policies with
 * `policy()`, grant with `grant()`, and expose writes through `definerFunction()`.
 *
 * ## Adding a privileged function
 *
 * `definerFunction()` builds a SECURITY DEFINER function owned by the definer role, with a pinned search_path and
 * EXECUTE limited to the runtime role. Bodies must schema-qualify every object (`public.users`).
 *
 * The roles are created by `bin/provision_db_roles.php`; their names are fixed here.
 */
final class RowLevelSecurity
{
    public const ROLE_APP = 'kualitet_app';
    public const ROLE_OWNER = 'kualitet_owner';
    public const ROLE_DEFINER = 'kualitet_definer';

    /**
     * Policy predicates. The helpers sit inside `(SELECT ...)` so PostgreSQL evaluates each one once per query
     * instead of once per row.
     */
    public const IS_SUPER = '(SELECT public.is_super())';
    public const DEV_IDS = '((SELECT public.dev_ids())::bigint[])';
    public const ADMIN_DEV_IDS = '((SELECT public.admin_dev_ids())::bigint[])';
    public const SESSION_USER_ID = '(SELECT public.session_user_id())';
    public const PERSON_ID = '(SELECT public.person_id())';

    /**
     * Columns that no managed domain table lets the runtime role update: the key and the development of a row.
     */
    private const FIXED_COLUMNS = ['id', 'development_id'];

    /**
     * Statements that turn row-level security on for a table, even for its owner.
     *
     * @param string $table Table name.
     * @return list<string>
     */
    public static function enable(string $table): array
    {
        $name = self::identifier($table);

        return [
            "ALTER TABLE {$name} ENABLE ROW LEVEL SECURITY",
            "ALTER TABLE {$name} FORCE ROW LEVEL SECURITY",
        ];
    }

    /**
     * Statements that undo enable().
     *
     * @param string $table Table name.
     * @return list<string>
     */
    public static function disable(string $table): array
    {
        $name = self::identifier($table);

        return [
            "ALTER TABLE {$name} NO FORCE ROW LEVEL SECURITY",
            "ALTER TABLE {$name} DISABLE ROW LEVEL SECURITY",
        ];
    }

    /**
     * One policy for one command, for the runtime role.
     *
     * @param string $table Table name.
     * @param string $command `SELECT`, `INSERT`, `UPDATE` or `DELETE`.
     * @param string|null $using Predicate for existing rows (SELECT, UPDATE, DELETE).
     * @param string|null $check Predicate for new rows (INSERT, UPDATE).
     * @param string|null $name Policy name; defaults to `<table>_<command>`.
     * @return string
     */
    public static function policy(
        string $table,
        string $command,
        ?string $using = null,
        ?string $check = null,
        ?string $name = null,
    ): string {
        if (!in_array($command, ['SELECT', 'INSERT', 'UPDATE', 'DELETE'], true)) {
            throw new InvalidArgumentException('Unknown policy command ' . $command);
        }
        $policy = self::identifier($name ?? ($table . '_' . strtolower($command)));
        $sql = sprintf(
            'CREATE POLICY %s ON %s AS PERMISSIVE FOR %s TO %s',
            $policy,
            self::identifier($table),
            $command,
            self::ROLE_APP,
        );
        if ($using !== null) {
            $sql .= " USING ({$using})";
        }
        if ($check !== null) {
            $sql .= " WITH CHECK ({$check})";
        }

        return $sql;
    }

    /**
     * Policies to drop with a table's row-level security (used by down()).
     *
     * @param string $table Table name.
     * @param list<string> $commands Commands that have a policy.
     * @return list<string>
     */
    public static function dropPolicies(
        string $table,
        array $commands = ['SELECT', 'INSERT', 'UPDATE', 'DELETE'],
    ): array {
        $statements = [];
        foreach ($commands as $command) {
            $statements[] = sprintf(
                'DROP POLICY IF EXISTS %s ON %s',
                self::identifier($table . '_' . strtolower($command)),
                self::identifier($table),
            );
        }

        return $statements;
    }

    /**
     * Grant the runtime role privileges on a table.
     *
     * @param string $table Table name.
     * @param string $privileges Privilege list, for example `SELECT, INSERT` or `UPDATE (ends_on, modified)`.
     * @return string
     */
    public static function grant(string $table, string $privileges): string
    {
        return sprintf('GRANT %s ON %s TO %s', $privileges, self::identifier($table), self::ROLE_APP);
    }

    /**
     * Grant the definer role (owner of the SECURITY DEFINER functions) privileges on a table.
     *
     * @param string $table Table name.
     * @param string $privileges Privilege list.
     * @return string
     */
    public static function grantDefiner(string $table, string $privileges = 'SELECT, INSERT, UPDATE, DELETE'): string
    {
        return sprintf('GRANT %s ON %s TO %s', $privileges, self::identifier($table), self::ROLE_DEFINER);
    }

    /**
     * Take every privilege on a table away from the runtime role and from PUBLIC.
     *
     * @param string $table Table name.
     * @return string
     */
    public static function revokeAll(string $table): string
    {
        return sprintf(
            'REVOKE ALL ON %s FROM %s, PUBLIC',
            self::identifier($table),
            self::ROLE_APP,
        );
    }

    /**
     * Policies and grants for a scoped domain table: rows with a NOT NULL `development_id`.
     *
     * SELECT, INSERT, UPDATE and DELETE all require `is_super() OR development_id = ANY(dev_ids())`. The rule is
     * coarse on purpose; per-role limits are layer 1 (DevelopmentScopedBehavior).
     *
     * @param string $table Table name.
     * @return list<string>
     */
    public static function scopedDomainTable(string $table): array
    {
        $scope = self::IS_SUPER . ' OR development_id = ANY (' . self::DEV_IDS . ')';

        return [
            ...self::enable($table),
            self::policy($table, 'SELECT', $scope),
            self::policy($table, 'INSERT', null, $scope),
            self::policy($table, 'UPDATE', $scope, $scope),
            self::policy($table, 'DELETE', $scope),
            self::grant($table, 'SELECT, INSERT, UPDATE, DELETE'),
            self::grantDefiner($table),
        ];
    }

    /**
     * Predicate for the developments where the session holds a permission (`permission_dev_ids`, AD7).
     *
     * @param string $code Permission code, `<module>.<action>` in lowercase letters and underscores.
     * @return string
     */
    public static function permissionDevIds(string $code): string
    {
        if (preg_match('/^[a-z_]+\.[a-z_]+$/D', $code) !== 1) {
            throw new InvalidArgumentException('Unsafe permission code ' . $code);
        }

        return "((SELECT public.permission_dev_ids('{$code}'))::bigint[])";
    }

    /**
     * Policies and grants for a domain table whose reads and writes follow permission codes (AD7, amended
     * 2026-11-19).
     *
     * - SELECT: `is_super() OR development_id = ANY(permission_dev_ids(readCode))`. The read code ends in `.view`,
     *   so a read-only assignment reads, a role without the code does not (a resident holding an assignment sees
     *   nothing), and a job reads nothing (`permission_dev_ids` is request-only).
     * - INSERT (WITH CHECK only) and UPDATE (USING and WITH CHECK):
     *   `is_super() OR development_id = ANY(permission_dev_ids(writeCode))`. The write code does not end in `.view`,
     *   so it needs a writable assignment and an unarchived development. The super-administrator is not narrowed by
     *   the archive state here; layer 1 refuses that write.
     * - DELETE: `is_super()` only (rows are deactivated or archived, not deleted).
     *
     * Write implies read: PostgreSQL applies the SELECT policy to `INSERT ... RETURNING`, to the WHERE of an UPDATE
     * and to a DELETE's WHERE. A role that holds the write code but not the read code can only run a bare INSERT (its
     * RETURNING is refused and its UPDATE matches no row). Every role that holds a write code must therefore also
     * hold the matching read code; AccessControlTest keeps that invariant for the seeds.
     *
     * Table contract:
     * - a NOT NULL `development_id` (a NULL row would match no policy) and a primary key generated by the database
     *   (`GENERATED BY DEFAULT AS IDENTITY` or `ALWAYS`); `id` is never insertable or updatable by the runtime role;
     * - references to other managed tables use composite foreign keys `(development_id, x_id)` to a unique
     *   `(development_id, id)`, and unique indexes are scoped per development. Foreign-key and unique checks bypass
     *   row-level security, so a plain `x_id` reference or a global unique index would let a caller probe whether a
     *   row exists in a development they cannot read;
     * - INSERT is granted on an explicit column list: `development_id`, the updatable columns and the insert-only
     *   ones. UPDATE is granted on the updatable columns only, never `id`, `development_id` or `created`, so a row
     *   cannot move to another development. List `modified` among the updatable columns and `created` among the
     *   insert-only ones;
     * - new ids come back through `RETURNING`: the CakePHP PostgreSQL driver appends `RETURNING *` to every insert and
     *   reads the id from that row (no `currval`), so no sequence privilege is granted, as for the other scoped
     *   tables. This works because the writer also reads the row (write implies read).
     *
     * @param string $table Table name.
     * @param string $readCode Permission code that guards reads, ends in `.view`, for example `units.view`.
     * @param string $writeCode Permission code that guards writes, does not end in `.view`, for example `units.manage`.
     * @param list<string> $updatableColumns Columns the runtime role may update (at least one, no duplicates).
     * @param list<string> $insertOnlyColumns Columns the runtime role may set on insert but never update, for
     *   example `created`.
     * @return list<string>
     */
    public static function managedDomainTable(
        string $table,
        string $readCode,
        string $writeCode,
        array $updatableColumns,
        array $insertOnlyColumns = [],
    ): array {
        if (!str_ends_with($readCode, '.view')) {
            throw new InvalidArgumentException('The read code ' . $readCode . ' must end in .view');
        }
        if (str_ends_with($writeCode, '.view')) {
            throw new InvalidArgumentException('The write code ' . $writeCode . ' must not end in .view');
        }
        if ($updatableColumns === []) {
            throw new InvalidArgumentException('A managed domain table needs at least one updatable column');
        }
        $read = self::IS_SUPER . ' OR development_id = ANY (' . self::permissionDevIds($readCode) . ')';
        $write = self::IS_SUPER . ' OR development_id = ANY (' . self::permissionDevIds($writeCode) . ')';

        foreach ($updatableColumns as $column) {
            if (in_array($column, [...self::FIXED_COLUMNS, 'created'], true)) {
                throw new InvalidArgumentException('The column ' . $column . ' cannot be updatable');
            }
        }
        foreach ($insertOnlyColumns as $column) {
            if (in_array($column, self::FIXED_COLUMNS, true)) {
                throw new InvalidArgumentException('The column ' . $column . ' cannot be listed for insert');
            }
        }
        $insertColumns = ['development_id', ...$updatableColumns, ...$insertOnlyColumns];
        foreach ($insertColumns as $column) {
            self::identifier($column);
        }
        if (count(array_unique($insertColumns)) !== count($insertColumns)) {
            throw new InvalidArgumentException('A column is listed twice');
        }

        return [
            ...self::enable($table),
            self::policy($table, 'SELECT', $read),
            self::policy($table, 'INSERT', null, $write),
            self::policy($table, 'UPDATE', $write, $write),
            self::policy($table, 'DELETE', self::IS_SUPER),
            self::grant($table, 'SELECT, DELETE'),
            self::grant($table, 'INSERT (' . implode(', ', $insertColumns) . ')'),
            self::grant($table, 'UPDATE (' . implode(', ', $updatableColumns) . ')'),
            self::grantDefiner($table),
        ];
    }

    /**
     * Policies and grants for a catalogue whose `development_id` is NULL for global rows.
     *
     * Everyone with access to a development reads its rows and the global ones. Only an administrator of the
     * development writes its own rows; global rows are edited by the super-administrator. A trigger forbids moving
     * a row to another development (or to global).
     *
     * @param string $table Table name.
     * @return list<string>
     */
    public static function catalogTable(string $table): array
    {
        $read = 'development_id IS NULL OR ' . self::IS_SUPER . ' OR development_id = ANY (' . self::DEV_IDS . ')';
        $write = self::IS_SUPER . ' OR (development_id IS NOT NULL AND development_id = ANY ('
            . self::ADMIN_DEV_IDS . '))';

        return [
            ...self::enable($table),
            self::policy($table, 'SELECT', $read),
            self::policy($table, 'INSERT', null, $write),
            self::policy($table, 'UPDATE', $write, $write),
            self::policy($table, 'DELETE', $write),
            self::grant($table, 'SELECT, INSERT, UPDATE, DELETE'),
            self::grantDefiner($table),
            sprintf(
                'CREATE TRIGGER %s BEFORE UPDATE ON %s FOR EACH ROW '
                . 'EXECUTE FUNCTION public.forbid_development_id_change()',
                self::identifier($table . '_forbid_development_change'),
                self::identifier($table),
            ),
        ];
    }

    /**
     * Statements that create a SECURITY DEFINER function owned by the definer role.
     *
     * The function pins `search_path = pg_catalog, pg_temp`, loses EXECUTE for PUBLIC and, unless it is a trigger
     * function, gains it for the runtime role only.
     *
     * @param string $name Function name (in schema public).
     * @param array<string, string> $parameters Parameter name => type.
     * @param string $returns Return type, `trigger`, or `TABLE (...)`.
     * @param string $language `sql` or `plpgsql`.
     * @param string $volatility `STABLE` or `VOLATILE`.
     * @param string $body Function body; every object must be schema-qualified.
     * @param bool $callableByApp Whether the runtime role may execute it (false for trigger functions).
     * @return list<string>
     */
    public static function definerFunction(
        string $name,
        array $parameters,
        string $returns,
        string $language,
        string $volatility,
        string $body,
        bool $callableByApp = true,
    ): array {
        $declared = [];
        $types = [];
        foreach ($parameters as $parameter => $type) {
            $declared[] = $parameter . ' ' . $type;
            $types[] = $type;
        }
        $signature = sprintf('public.%s(%s)', $name, implode(', ', $types));

        $statements = [
            sprintf(
                'CREATE OR REPLACE FUNCTION public.%s(%s) RETURNS %s LANGUAGE %s %s SECURITY DEFINER '
                . 'SET search_path = pg_catalog, pg_temp AS $fn$%s$fn$',
                $name,
                implode(', ', $declared),
                $returns,
                $language,
                $volatility,
                $body,
            ),
            ...self::giveToDefiner($signature),
            sprintf('REVOKE ALL ON FUNCTION %s FROM PUBLIC', $signature),
        ];
        if ($callableByApp) {
            $statements[] = sprintf('GRANT EXECUTE ON FUNCTION %s TO %s', $signature, self::ROLE_APP);
        }

        return $statements;
    }

    /**
     * Statements that hand a function over to the definer role.
     *
     * `ALTER FUNCTION ... OWNER TO` requires the new owner to have CREATE on the schema. The definer role is NOLOGIN
     * and must not keep that privilege (a function running as it could otherwise create objects in `public`), so it is
     * granted for these statements only and revoked straight away. Runs as the migration login, which owns the schema.
     *
     * @param string $signature Function with its argument types, for example `public.is_super()`.
     * @return list<string>
     */
    public static function giveToDefiner(string $signature): array
    {
        return [
            'GRANT CREATE ON SCHEMA public TO ' . self::ROLE_DEFINER,
            sprintf('ALTER FUNCTION %s OWNER TO %s', $signature, self::ROLE_DEFINER),
            'REVOKE CREATE ON SCHEMA public FROM ' . self::ROLE_DEFINER,
        ];
    }

    /**
     * @param string $name Function name (in schema public).
     * @param list<string> $types Parameter types.
     * @return string
     */
    public static function dropFunction(string $name, array $types = []): string
    {
        return sprintf('DROP FUNCTION IF EXISTS public.%s(%s)', $name, implode(', ', $types));
    }

    /**
     * @param string $name Table or policy name.
     * @return string
     */
    private static function identifier(string $name): string
    {
        if (preg_match('/^[a-z_][a-z0-9_]*$/D', $name) !== 1) {
            throw new InvalidArgumentException('Unsafe identifier ' . $name);
        }

        return $name;
    }
}
