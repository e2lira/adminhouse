<?php
declare(strict_types=1);

namespace App\Test\TestCase\Database\Rls;

use App\Database\RowLevelSecurity;
use Cake\ORM\Table;
use InvalidArgumentException;
use PHPUnit\Framework\Attributes\DataProvider;
use Throwable;

/**
 * Managed domain tables (AD7, amended 2026-11-19): reads follow the read permission and writes follow the write
 * permission, both through `permission_dev_ids(code)`; only the super-administrator deletes. A throwaway table guarded
 * by the seeded codes `units.view` (administrator, accountant, data_entry and supervisor hold it; guard and resident
 * do not) and `units.manage` (administrator and data_entry) proves the generated policies and grants.
 *
 * Not parallel-safe: the table name `probe_managed` is shared, like the other probe tables of this suite.
 */
class RlsManagedDomainTableTest extends RlsTestCase
{
    private const READ = 'units.view';

    private const WRITE = 'units.manage';

    protected function setUp(): void
    {
        parent::setUp();

        $this->dropProbeTable();
        $this->db()->execute(
            'CREATE TABLE probe_managed (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                development_id bigint NOT NULL REFERENCES developments (id), label text NOT NULL,
                created timestamp NOT NULL DEFAULT now(), modified timestamp NULL)',
        );
        $statements = RowLevelSecurity::managedDomainTable(
            'probe_managed',
            self::READ,
            self::WRITE,
            ['label', 'modified'],
            ['created'],
        );
        foreach ($statements as $sql) {
            $this->db()->execute($sql);
        }
        $this->db()->execute(
            "INSERT INTO probe_managed (development_id, label) VALUES (?, 'a1'), (?, 'a2'), (?, 'b1')",
            [$this->devA, $this->devA, $this->devB],
        );
    }

    protected function tearDown(): void
    {
        parent::tearDown();
        $this->dropProbeTable();
    }

    private function dropProbeTable(): void
    {
        $this->db()->execute('DROP TABLE IF EXISTS probe_managed');
    }

    /**
     * @return list<string>
     */
    private function labels(): array
    {
        $rows = $this->appDb()->execute('SELECT label FROM probe_managed ORDER BY label')->fetchAll();

        return array_map(static fn(array $row): string => $row[0], $rows);
    }

    /**
     * @return array<string, array{string}>
     */
    public static function invalidCodes(): array
    {
        return [
            'no dot' => ['units'],
            'uppercase' => ['Units.manage'],
            'digit' => ['units.manage2'],
            'dash' => ['units.manage-all'],
            'three parts' => ['units.manage.all'],
            'quote' => ["units.manage'"],
            'injection' => ["units.manage') OR (1=1"],
            'semicolon' => ['units.manage;'],
            'space' => ['units. manage'],
            'trailing newline' => ["units.manage\n"],
            'empty' => [''],
        ];
    }

    #[DataProvider('invalidCodes')]
    public function testAReadCodeThatIsNotModuleDotActionIsRejected(string $code): void
    {
        $this->expectException(InvalidArgumentException::class);

        RowLevelSecurity::managedDomainTable('probe_managed', $code, self::WRITE, ['label']);
    }

    #[DataProvider('invalidCodes')]
    public function testAWriteCodeThatIsNotModuleDotActionIsRejected(string $code): void
    {
        $this->expectException(InvalidArgumentException::class);

        RowLevelSecurity::managedDomainTable('probe_managed', self::READ, $code, ['label']);
    }

    #[DataProvider('invalidCodes')]
    public function testThePredicateBuilderRejectsTheSameCodes(string $code): void
    {
        $this->expectException(InvalidArgumentException::class);

        RowLevelSecurity::permissionDevIds($code);
    }

    public function testThePredicateIsAQuotedCallToTheFunction(): void
    {
        $this->assertSame(
            "((SELECT public.permission_dev_ids('units.manage'))::bigint[])",
            RowLevelSecurity::permissionDevIds('units.manage'),
        );
    }

    public function testEveryBuilderRejectsAnIdentifierWithATrailingNewline(): void
    {
        $calls = [
            static fn() => RowLevelSecurity::enable("probe\n"),
            static fn() => RowLevelSecurity::scopedDomainTable("probe\n"),
            static fn() => RowLevelSecurity::grant("probe\n", 'SELECT'),
        ];
        foreach ($calls as $call) {
            try {
                $call();
                $this->fail('A trailing newline was accepted');
            } catch (InvalidArgumentException $e) {
                $this->assertStringContainsString('Unsafe identifier', $e->getMessage());
            }
        }
        // The control: the same name without the newline is accepted.
        $this->assertNotSame([], RowLevelSecurity::enable('probe'));
    }

