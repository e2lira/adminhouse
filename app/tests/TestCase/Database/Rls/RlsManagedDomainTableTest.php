<?php
declare(strict_types=1);

namespace App\Test\TestCase\Database\Rls;

use App\Database\RowLevelSecurity;
use InvalidArgumentException;
use PHPUnit\Framework\Attributes\DataProvider;

/**
 * Managed domain tables (AD7): reads follow `dev_ids()`, writes follow the permission catalogue through
 * `permission_dev_ids(code)`, and only the super-administrator deletes. A throwaway table guarded by the seeded code
 * `payments.create` (administrator, accountant and data_entry hold it; supervisor, guard and resident do not) proves
 * the generated policies and grants.
 */
class RlsManagedDomainTableTest extends RlsTestCase
{
    private const CODE = 'payments.create';

    protected function setUp(): void
    {
        parent::setUp();

        $this->dropProbeTable();
        $this->db()->execute(
            'CREATE TABLE probe_managed (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                development_id bigint NOT NULL REFERENCES developments (id), label text NOT NULL)',
        );
        foreach (RowLevelSecurity::managedDomainTable('probe_managed', self::CODE, ['label']) as $sql) {
            $this->db()->execute($sql);
        }
        $this->db()->execute(
            "INSERT INTO probe_managed (development_id, label) VALUES (?, 'a1'), (?, 'a2'), (?, 'b1')",
            [$this->devA, $this->devA, $this->devB],
        );
    }

    protected function tearDown(): void
    {
        parent::tearDown();
        $this->dropProbeTable();
    }

    private function dropProbeTable(): void
    {
        $this->db()->execute('DROP TABLE IF EXISTS probe_managed');
    }

    /**
     * @return list<string>
     */
    private function labels(): array
    {
        $rows = $this->appDb()->execute('SELECT label FROM probe_managed ORDER BY label')->fetchAll();

        return array_map(static fn(array $row): string => $row[0], $rows);
    }

    /**
     * @return array<string, array{string}>
     */
    public static function invalidCodes(): array
    {
        return [
            'no dot' => ['units'],
            'uppercase' => ['Units.manage'],
            'digit' => ['units.manage2'],
            'dash' => ['units.manage-all'],
            'three parts' => ['units.manage.all'],
            'quote' => ["units.manage'"],
            'injection' => ["units.manage') OR (1=1"],
            'semicolon' => ['units.manage;'],
            'space' => ['units. manage'],
            'trailing newline' => ["units.manage\n"],
            'empty' => [''],
        ];
    }

    #[DataProvider('invalidCodes')]
    public function testACodeThatIsNotModuleDotActionIsRejected(string $code): void
    {
        $this->expectException(InvalidArgumentException::class);

        RowLevelSecurity::managedDomainTable('probe_managed', $code, ['label']);
    }

    #[DataProvider('invalidCodes')]
    public function testThePredicateBuilderRejectsTheSameCodes(string $code): void
    {
        $this->expectException(InvalidArgumentException::class);

        RowLevelSecurity::permissionDevIds($code);
    }

    public function testThePredicateIsAQuotedCallToTheFunction(): void
    {
        $this->assertSame(
            "((SELECT public.permission_dev_ids('units.manage'))::bigint[])",
            RowLevelSecurity::permissionDevIds('units.manage'),
        );
    }

    /**
     * @return array<string, array{string, list<string>}>
     */
    public static function invalidUpdatableColumns(): array
    {
        return [
            'primary key' => ['units', ['id']],
            'development among others' => ['units', ['label', 'development_id']],
            'none' => ['units', []],
            'unsafe name' => ['units', ['label; DROP TABLE x']],
            'unsafe table' => ['units; DROP', ['label']],
        ];
    }

    /**
     * @param string $table Table.
     * @param list<string> $columns Columns.
     * @return void
     */
    #[DataProvider('invalidUpdatableColumns')]
    public function testOnlySafeNonKeyColumnsMayBeUpdatable(string $table, array $columns): void
    {
        $this->expectException(InvalidArgumentException::class);

        RowLevelSecurity::managedDomainTable($table, self::CODE, $columns);
    }

    public function testReadsFollowTheDevelopmentsOfTheSession(): void
    {
        foreach (['adminA', 'accountantA', 'dataEntryA', 'guardA', 'resident'] as $user) {
            $this->actAs($this->{$user});
            $this->assertSame(['a1', 'a2'], $this->labels(), $user);
            $this->endSession();
        }
        $this->actAs($this->adminB);
        $this->assertSame(['b1'], $this->labels());
        $this->endSession();

        foreach (['disabledAdmin', 'endedAdmin', 'futureAdmin', 'loner'] as $user) {
            $this->actAs($this->{$user});
            $this->assertSame([], $this->labels(), $user);
            $this->endSession();
        }
        $this->actAs($this->superUser);
        $this->assertSame(['a1', 'a2', 'b1'], $this->labels());
        $this->endSession();

        $this->actAsJob([$this->devB]);
        $this->assertSame(['b1'], $this->labels());
    }

    /**
     * @return array<string, array{string}>
     */
    public static function holders(): array
    {
        return [
            'administrator' => ['adminA'],
            'accountant' => ['accountantA'],
            'data entry' => ['dataEntryA'],
        ];
    }

    /**
     * @param string $user Property holding the user id.
     * @return void
     */
    #[DataProvider('holders')]
    public function testAHolderOfTheCodeInsertsAndUpdatesInItsDevelopmentOnly(string $user): void
    {
        $this->actAs($this->{$user});

        $this->assertAllowed("INSERT INTO probe_managed (development_id, label) VALUES (?, 'new')", [$this->devA]);
        $this->assertRejected("INSERT INTO probe_managed (development_id, label) VALUES (?, 'new')", [$this->devB]);
        $this->assertAllowed("UPDATE probe_managed SET label = 'x' WHERE label = 'a1'");
        $this->assertDenied("UPDATE probe_managed SET label = 'x' WHERE label = 'b1'");
    }

    /**
     * @return array<string, array{string}>
     */
    public static function nonHolders(): array
    {
        return [
            'guard (sees the rows, role lacks the code)' => ['guardA'],
            'resident (sees the rows, role lacks the code)' => ['resident'],
            'administrator of the other development' => ['adminB'],
            'disabled administrator' => ['disabledAdmin'],
            'ended assignment' => ['endedAdmin'],
            'future assignment' => ['futureAdmin'],
            'user without assignments' => ['loner'],
        ];
    }

    /**
     * @param string $user Property holding the user id.
     * @return void
     */
    #[DataProvider('nonHolders')]
    public function testWhoLacksTheCodeCannotWrite(string $user): void
    {
        $this->actAs($this->{$user});

        $this->assertRejected("INSERT INTO probe_managed (development_id, label) VALUES (?, 'new')", [$this->devA]);
        $this->assertDenied("UPDATE probe_managed SET label = 'x' WHERE label = 'a1'");
    }

    public function testAReadOnlyAssignmentCannotWrite(): void
    {
        $user = $this->createUser('observer', null);
        $this->assignRole($user, 'accountant', $this->devA, -30, null, true);
        $this->actAs($user);

        $this->assertSame(['a1', 'a2'], $this->labels());
        $this->assertRejected("INSERT INTO probe_managed (development_id, label) VALUES (?, 'new')", [$this->devA]);
        $this->assertDenied("UPDATE probe_managed SET label = 'x' WHERE label = 'a1'");
    }

    public function testAnArchivedDevelopmentCanBeReadButNotWritten(): void
    {
        $this->db()->execute('UPDATE developments SET archived_at = NOW() WHERE id = ?', [$this->devA]);
        $this->actAs($this->adminA);

        $this->assertSame(['a1', 'a2'], $this->labels());
        $this->assertRejected("INSERT INTO probe_managed (development_id, label) VALUES (?, 'new')", [$this->devA]);
        $this->assertDenied("UPDATE probe_managed SET label = 'x' WHERE label = 'a1'");
    }

    public function testTheSuperAdministratorWritesAnywhere(): void
    {
        $this->actAs($this->superUser);

        $this->assertAllowed("INSERT INTO probe_managed (development_id, label) VALUES (?, 'new')", [$this->devB]);
        $this->assertAllowed("UPDATE probe_managed SET label = 'x' WHERE label = 'b1'");
    }

    public function testAJobAndASessionlessRequestCannotWrite(): void
    {
        $this->actAs(null);
        $this->assertRejected("INSERT INTO probe_managed (development_id, label) VALUES (?, 'new')", [$this->devA]);
        $this->assertDenied("UPDATE probe_managed SET label = 'x'");
        $this->endSession();

        $this->actAsJob([$this->devA]);
        $this->assertSame(['a1', 'a2'], $this->labels());
        $this->assertRejected("INSERT INTO probe_managed (development_id, label) VALUES (?, 'new')", [$this->devA]);
        $this->assertDenied("UPDATE probe_managed SET label = 'x'");
    }

    public function testOnlyTheSuperAdministratorDeletes(): void
    {
        foreach (['adminA', 'accountantA', 'dataEntryA'] as $user) {
            $this->actAs($this->{$user});
            $this->assertDenied("DELETE FROM probe_managed WHERE label = 'a1'");
            $this->endSession();
        }
        $this->actAsJob([$this->devA]);
        $this->assertDenied("DELETE FROM probe_managed WHERE label = 'a1'");
        $this->endSession();

        $this->actAs($this->superUser);
        $this->assertAllowed("DELETE FROM probe_managed WHERE label = 'a1'");
        $this->commitSession();

        $this->assertSame(
            ['a2', 'b1'],
            array_map(
                static fn(array $row): string => $row[0],
                $this->db()->execute('SELECT label FROM probe_managed ORDER BY label')->fetchAll(),
            ),
        );
    }

    public function testNoRoleCanMoveARowToAnotherDevelopmentOrChangeItsKey(): void
    {
        foreach (['adminA', 'superUser'] as $user) {
            $this->actAs($this->{$user});
            // Column privileges: only `label` is updatable, so these are refused even where the row policy allows.
            $this->assertRejected('UPDATE probe_managed SET development_id = ? WHERE label = ?', [$this->devB, 'a1']);
            $this->assertRejected('UPDATE probe_managed SET id = id + 100 WHERE label = ?', ['a1']);
            $this->assertAllowed("UPDATE probe_managed SET label = 'kept' WHERE label = 'a2'");
            $this->endSession();
        }
    }
}
