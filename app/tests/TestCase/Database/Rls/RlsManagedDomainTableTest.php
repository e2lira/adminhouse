    public function testTheRuntimeRoleHoldsExactlyTheColumnPrivilegesTheContractNames(): void
    {
        $privilege = fn(string $kind, string $column): bool => (bool)$this->db()->execute(
            'SELECT has_column_privilege(?, ?, ?, ?)',
            [RowLevelSecurity::ROLE_APP, 'probe_managed', $column, $kind],
        )->fetch()[0];

        foreach (['label', 'modified'] as $column) {
            $this->assertTrue($privilege('UPDATE', $column), 'UPDATE ' . $column);
        }
        foreach (['id', 'development_id', 'created'] as $column) {
            $this->assertFalse($privilege('UPDATE', $column), 'UPDATE ' . $column);
        }
        foreach (['development_id', 'label', 'modified', 'created'] as $column) {
            $this->assertTrue($privilege('INSERT', $column), 'INSERT ' . $column);
        }
        $this->assertFalse($privilege('INSERT', 'id'), 'INSERT id');
    }

    public function testAnIdCannotBeChosenOnInsert(): void
    {
        $this->actAs($this->superUser);

        $this->assertRejected(
            "INSERT INTO probe_managed (id, development_id, label) VALUES (9999, ?, 'x')",
            [$this->devA],
        );
        $this->assertAllowed(
            "INSERT INTO probe_managed (development_id, label, created) VALUES (?, 'x', now())",
            [$this->devA],
        );
    }

    public function testReadsFollowTheReadPermissionOfTheSession(): void
    {
        foreach (['adminA', 'accountantA', 'dataEntryA'] as $user) {
            $this->actAs($this->{$user});
            $this->assertSame(['a1', 'a2'], $this->labels(), $user);
            $this->endSession();
        }
        $this->actAs($this->adminB);
        $this->assertSame(['b1'], $this->labels());
        $this->endSession();

        // They hold an assignment in A (dev_ids() lists A) but their role lacks the read code.
        foreach (['resident', 'guardA'] as $user) {
            $this->actAs($this->{$user});
            $this->assertSame([$this->devA], $this->ids('SELECT unnest(dev_ids())'), $user);
            $this->assertSame([], $this->labels(), $user);
            $this->endSession();
        }
        foreach (['disabledAdmin', 'endedAdmin', 'futureAdmin', 'loner'] as $user) {
            $this->actAs($this->{$user});
            $this->assertSame([], $this->labels(), $user);
            $this->endSession();
        }
        $this->actAs($this->superUser);
        $this->assertSame(['a1', 'a2', 'b1'], $this->labels());
    }

    public function testAReadOnlyAssignmentReadsButDoesNotWrite(): void
    {
        $user = $this->createUser('observer', null);
        $this->assignRole($user, 'administrator', $this->devA, -30, null, true);
        $this->actAs($user);

        $this->assertSame(['a1', 'a2'], $this->labels());
        $this->assertRejected("INSERT INTO probe_managed (development_id, label) VALUES (?, 'new')", [$this->devA]);
        $this->assertDenied("UPDATE probe_managed SET label = 'x' WHERE label = 'a1'");
        $this->assertDenied('DELETE FROM probe_managed');

        // The rows are visible to this session and still unchanged: the denial is real, not an empty match.
        $this->assertSame(['a1', 'a2'], $this->labels());
        $this->assertRowsUntouched();
    }

    public function testAJobReadsNothing(): void
    {
        $this->actAsJob([$this->devA, $this->devB]);

        // dev_ids() would list both developments in a job; the read permission is request-only.
        $this->assertSame([$this->devA, $this->devB], $this->ids('SELECT unnest(dev_ids())'));
        $this->assertSame([], $this->labels());
    }

    public function testASessionlessRequestReadsNothing(): void
    {
        $this->actAs(null);

        $this->assertSame([], $this->labels());
    }

    public function testAnArchivedDevelopmentCanBeReadButNotWritten(): void
    {
        $this->db()->execute('UPDATE developments SET archived_at = NOW() WHERE id = ?', [$this->devA]);
        $this->actAs($this->adminA);

        $this->assertSame(['a1', 'a2'], $this->labels());
        $this->assertRejected("INSERT INTO probe_managed (development_id, label) VALUES (?, 'new')", [$this->devA]);
        $this->assertDenied("UPDATE probe_managed SET label = 'x' WHERE label = 'a1'");
    }

    public function testTheSuperAdministratorWritesInAnArchivedDevelopmentBecauseLayerOneRefusesIt(): void
    {
        // W-E: the database does not narrow is_super(); DevelopmentPolicy::canManage* is what refuses this write.
        $this->db()->execute('UPDATE developments SET archived_at = NOW() WHERE id = ?', [$this->devA]);
        $this->actAs($this->superUser);

        $this->assertAllowed("INSERT INTO probe_managed (development_id, label) VALUES (?, 'new')", [$this->devA]);
        $this->assertAllowed("UPDATE probe_managed SET label = 'x' WHERE label = 'a1'");
    }

