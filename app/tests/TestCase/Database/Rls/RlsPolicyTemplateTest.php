<?php
declare(strict_types=1);

namespace App\Test\TestCase\Database\Rls;

use App\Database\RowLevelSecurity;

/**
 * The reusable pattern future modules plug into (ADR-0005 s.1 table classes): a scoped domain table and a catalog
 * table get their policies from RowLevelSecurity, without writing any SQL policy by hand. A throwaway table of each
 * kind proves the generated policies behave as the ADR table says.
 */
class RlsPolicyTemplateTest extends RlsTestCase
{
    protected function setUp(): void
    {
        parent::setUp();

        $this->dropProbeTables();
        $this->db()->execute(
            'CREATE TABLE probe_units (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                development_id bigint NOT NULL REFERENCES developments (id), label text NOT NULL)',
        );
        $this->db()->execute(
            'CREATE TABLE probe_catalog (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                development_id bigint REFERENCES developments (id), label text NOT NULL)',
        );
        foreach (RowLevelSecurity::scopedDomainTable('probe_units') as $sql) {
            $this->db()->execute($sql);
        }
        foreach (RowLevelSecurity::catalogTable('probe_catalog') as $sql) {
            $this->db()->execute($sql);
        }

        $this->db()->execute(
            "INSERT INTO probe_units (development_id, label) VALUES (?, 'a1'), (?, 'a2'), (?, 'b1')",
            [$this->devA, $this->devA, $this->devB],
        );
        $this->db()->execute(
            "INSERT INTO probe_catalog (development_id, label) VALUES (NULL, 'global'), (?, 'a-own'), (?, 'b-own')",
            [$this->devA, $this->devB],
        );
    }

    protected function tearDown(): void
    {
        parent::tearDown();
        $this->dropProbeTables();
    }

    private function dropProbeTables(): void
    {
        $this->db()->execute('DROP TABLE IF EXISTS probe_units');
        $this->db()->execute('DROP TABLE IF EXISTS probe_catalog');
    }

    /**
     * @param string $table Table.
     * @return list<string>
     */
    private function labels(string $table): array
    {
        $rows = $this->appDb()->execute("SELECT label FROM {$table} ORDER BY label")->fetchAll();

        return array_map(static fn(array $row): string => $row[0], $rows);
    }

    public function testScopedDomainTableReadsFollowTheDevelopments(): void
    {
        $this->actAs(null);
        $this->assertSame([], $this->labels('probe_units'));
        $this->endSession();

        foreach (['adminA', 'accountantA', 'resident', 'guardA'] as $user) {
            $this->actAs($this->{$user});
            $this->assertSame(['a1', 'a2'], $this->labels('probe_units'), $user);
            $this->endSession();
        }
        foreach (['disabledAdmin', 'endedAdmin', 'futureAdmin', 'loner'] as $user) {
            $this->actAs($this->{$user});
            $this->assertSame([], $this->labels('probe_units'), $user);
            $this->endSession();
        }
        $this->actAs($this->superUser);
        $this->assertSame(['a1', 'a2', 'b1'], $this->labels('probe_units'));
        $this->endSession();

        $this->actAsJob([$this->devB]);
        $this->assertSame(['b1'], $this->labels('probe_units'));
    }

    public function testScopedDomainTableWritesStayInsideTheDevelopments(): void
    {
        $this->actAs($this->accountantA);

        $this->assertAllowed("INSERT INTO probe_units (development_id, label) VALUES (?, 'new')", [$this->devA]);
        $this->assertRejected("INSERT INTO probe_units (development_id, label) VALUES (?, 'new')", [$this->devB]);
        $this->assertAllowed("UPDATE probe_units SET label = 'x' WHERE label = 'a1'");
        $this->assertDenied("UPDATE probe_units SET label = 'x' WHERE label = 'b1'");
        // Moving a row to another development is a write to that development.
        $this->assertRejected('UPDATE probe_units SET development_id = ? WHERE label = ?', [$this->devB, 'a2']);
        $this->assertAllowed("DELETE FROM probe_units WHERE label = 'a2'");
        $this->assertDenied("DELETE FROM probe_units WHERE label = 'b1'");
    }

    public function testScopedDomainTableIsClosedWithoutASession(): void
    {
        $this->actAs(null);

        $this->assertRejected("INSERT INTO probe_units (development_id, label) VALUES (?, 'new')", [$this->devA]);
        $this->assertDenied('DELETE FROM probe_units');
    }

    public function testCatalogReadsIncludeGlobalRows(): void
    {
        $this->actAs($this->resident);
        $this->assertSame(['a-own', 'global'], $this->labels('probe_catalog'));
        $this->endSession();

        $this->actAs($this->loner);
        $this->assertSame(['global'], $this->labels('probe_catalog'));
        $this->endSession();

        $this->actAs($this->superUser);
        $this->assertSame(['a-own', 'b-own', 'global'], $this->labels('probe_catalog'));
    }

    public function testCatalogWritesNeedAnAdministratorOfThatDevelopment(): void
    {
        $this->actAs($this->adminA);

        $this->assertAllowed("INSERT INTO probe_catalog (development_id, label) VALUES (?, 'mine')", [$this->devA]);
        $this->assertRejected("INSERT INTO probe_catalog (development_id, label) VALUES (NULL, 'global2')");
        $this->assertRejected("INSERT INTO probe_catalog (development_id, label) VALUES (?, 'theirs')", [$this->devB]);
        $this->assertAllowed("UPDATE probe_catalog SET label = 'renamed' WHERE label = 'a-own'");
        $this->assertDenied("UPDATE probe_catalog SET label = 'hacked' WHERE label = 'global'");
        $this->assertDenied("DELETE FROM probe_catalog WHERE label = 'global'");
        $this->endSession();

        $this->actAs($this->accountantA);
        $this->assertRejected("INSERT INTO probe_catalog (development_id, label) VALUES (?, 'x')", [$this->devA]);
    }

    public function testCatalogItemsNeverChangeDevelopment(): void
    {
        $this->actAs($this->superUser);

        $this->assertRejected('UPDATE probe_catalog SET development_id = ? WHERE label = ?', [$this->devB, 'a-own']);
        $this->assertRejected('UPDATE probe_catalog SET development_id = NULL WHERE label = ?', ['a-own']);
    }

    public function testSuperAdministratorEditsGlobalCatalogItems(): void
    {
        $this->actAs($this->superUser);

        $this->assertAllowed("UPDATE probe_catalog SET label = 'global v2' WHERE label = 'global'");
        $this->assertAllowed("INSERT INTO probe_catalog (development_id, label) VALUES (NULL, 'global 3')");
    }

    public function testTheGeneratedSqlForcesRowLevelSecurity(): void
    {
        $this->assertSame(RowLevelSecurity::scopedDomainTable('t'), RowLevelSecurity::scopedDomainTable('t'));
        $this->assertStringContainsString(
            'FORCE ROW LEVEL SECURITY',
            implode("\n", RowLevelSecurity::scopedDomainTable('t')),
        );
        $this->assertStringContainsString(
            'FORCE ROW LEVEL SECURITY',
            implode("\n", RowLevelSecurity::catalogTable('t')),
        );
    }
}
