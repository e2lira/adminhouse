<?php
namespace App\Model\Table;

use Cake\ORM\Query;
use Cake\ORM\RulesChecker;
use Cake\ORM\Table;
use Cake\Validation\Validator;

/**
 * Ticket Model
 *
 * @method \App\Model\Entity\Ticket get($primaryKey, $options = [])
 * @method \App\Model\Entity\Ticket newEntity($data = null, array $options = [])
 * @method \App\Model\Entity\Ticket[] newEntities(array $data, array $options = [])
 * @method \App\Model\Entity\Ticket|false save(\Cake\Datasource\EntityInterface $entity, $options = [])
 * @method \App\Model\Entity\Ticket saveOrFail(\Cake\Datasource\EntityInterface $entity, $options = [])
 * @method \App\Model\Entity\Ticket patchEntity(\Cake\Datasource\EntityInterface $entity, array $data, array $options = [])
 * @method \App\Model\Entity\Ticket[] patchEntities($entities, array $data, array $options = [])
 * @method \App\Model\Entity\Ticket findOrCreate($search, callable $callback = null, $options = [])
 */
class TicketTable extends Table
{
    /**
     * Initialize method
     *
     * @param array $config The configuration for the Table.
     * @return void
     */
    public function initialize(array $config)
    {
        parent::initialize($config);

        $this->setTable('ticket');
        $this->setDisplayField('id_ticket');
        $this->setPrimaryKey('id_ticket');

        $this->addBehavior('Josegonzalez/Upload.Upload', [
            'adjunto'=> []
        ]);
    }

    /**
     * Default validation rules.
     *
     * @param \Cake\Validation\Validator $validator Validator instance.
     * @return \Cake\Validation\Validator
     */
    public function validationDefault(Validator $validator)
    {
        $validator
            ->integer('id_ticket')
            ->allowEmptyString('id_ticket', null, 'create');

        $validator
            ->integer('id_condominio')
            ->allowEmptyString('id_condominio');

        $validator
            ->integer('id_condomino')
            ->allowEmptyString('id_condomino');

        $validator
            ->scalar('nombre')
            ->maxLength('nombre', 145)
            ->allowEmptyString('nombre');

        $validator
            ->scalar('prioridad')
            ->maxLength('prioridad', 45)
            ->allowEmptyString('prioridad');

        $validator
            ->scalar('asunto')
            ->maxLength('asunto', 45)
            ->allowEmptyString('asunto');

        $validator
            ->scalar('mensaje')
            ->allowEmptyString('mensaje');


        $validator
            ->allowEmptyString('adjunto');

        return $validator;
    }
}
